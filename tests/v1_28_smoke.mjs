import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
import {KPA_TO_PSF,calculateSnow} from '../ewp-tools/snow-load/calc.mjs';
import {loadPair,parseLoadPressure,formatLoadPressure,displayLoadPair} from '../ewp-tools/snow-load/load-units.mjs';
let n=0;const check=(description,fn)=>{fn();n++;console.log('PASS',description);};
const near=(x,y,eps=1e-9)=>assert.ok(Math.abs(x-y)<eps,`${x} != ${y}`);
check('positive pressure parsed',()=>assert.equal(parseLoadPressure('2.6'),2.6));
check('zero valid pressure',()=>assert.equal(parseLoadPressure('0'),0));
check('zero not same as blank',()=>assert.equal(parseLoadPressure(''),null));
check('spaces blank',()=>assert.equal(parseLoadPressure('  '),null));
check('negative load rejected',()=>assert.ok(Number.isNaN(parseLoadPressure('-1'))));
check('malformed text rejected',()=>assert.ok(Number.isNaN(parseLoadPressure('abc'))));
check('partial decimal rejected',()=>assert.ok(Number.isNaN(parseLoadPressure('.'))));
check('scientific valid',()=>near(parseLoadPressure('2.6e-2'),.026));
check('Infinity rejected',()=>assert.ok(Number.isNaN(parseLoadPressure('Infinity'))));
check('separators rejected',()=>assert.ok(Number.isNaN(parseLoadPressure('1,200'))));
check('1 kPa to psf',()=>near(loadPair('1','kpa').other,formatLoadPressure(KPA_TO_PSF,'psf')*1,0.01));
check('Ss 2.6 kPa -> 54.30 psf',()=>assert.equal(loadPair('2.6','kpa').other,'54.3'));
check('Sr 0.3 kPa -> 6.27 psf',()=>assert.equal(loadPair('0.3','kpa').other,'6.27'));
check('54.3 psf kPa original precision',()=>near(loadPair('54.3','psf').kpa,54.3/KPA_TO_PSF));
check('50 psf kPa display',()=>assert.equal(loadPair('50','psf').other,'2.394013'));
check('format tiny nonzero kPa',()=>assert.notEqual(formatLoadPressure(0.00000001,'kpa'),'0'));
check('source string preserved',()=>assert.equal(loadPair('02.600','kpa').source,'02.600'));
check('empty paired field',()=>assert.deepEqual(loadPair('','psf'),{source:'',other:'',kpa:null,valid:false}));
check('invalid paired field',()=>assert.ok(Number.isNaN(loadPair('oops','psf').kpa)));
check('display preserves original psf',()=>assert.equal(displayLoadPair({unit:'psf',value:'50'}).psf,'50'));
check('display preserves original kpa',()=>assert.equal(displayLoadPair({unit:'kpa',value:'2.6'}).kpa,'2.6'));
check('invalid unit rejected',()=>assert.throws(()=>loadPair('1','psi'),RangeError));
check('formula from direct kPa same as old',()=>near(calculateSnow(2.6,.3,.8).kpa,2.38));
check('formula from psf uses original precision',()=>near(calculateSnow(loadPair('54.3','psf').kpa,loadPair('6.27','psf').kpa,.8).kpa,(54.3*.8+6.27)/KPA_TO_PSF));
check('part9 minimum unaffected',()=>assert.equal(calculateSnow(.2,.1,.55,true).kpa,1));
