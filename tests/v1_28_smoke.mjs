check('standalone converter panel removed',()=>assert.doesNotMatch(html,/Quick Unit Converter|snow-converter-panel|pressureKpa|pressurePsf|pressureClear/));
check('standalone converter script removed',()=>assert.doesNotMatch(html,/pressure-converter\.mjs/));
check('legacy converter styles removed',()=>assert.doesNotMatch(style,/\.snow-converter-panel|\.snow-converter-fields|\.snow-converter-separator/));
check('BC location input read-only set by app',()=>assert.match(app,/readOnly=isLocation/));
check('original typed pressure used for calc',()=>assert.match(app,/loadPair\(state\.custom\.ss\.value,state\.custom\.ss\.unit\)\.kpa/));
check('all four fields registered for input',()=>assert.match(app,/\[\['ss','snowSs','snowSsPsf'\],\['sr','snowSr','snowSrPsf'\]\]/));
check('BC country autocomplete unchanged',()=>assert.match(app,/requestGeo\(query,seq,locals,state\.controller\.signal\)/));
check('BC reference explicit selection preserved',()=>assert.match(app,/chooseCode\(item/));
check('part 9 factor stays',()=>assert.match(html,/value="0\.55"/));
